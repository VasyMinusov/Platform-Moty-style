import { QueryClient } from '@tanstack/react-query'

/**
 * Глобальный клиент React Query.
 *
 * Настройки по умолчанию (для всех запросов):
 * - staleTime: 30 секунд — данные считаются «свежими» полминуты.
 *   В течение этого времени react-query не будет ходить на сервер,
 *   даже если компонент перемонтировался. При переходе между страницами
 *   данные берутся из кэша мгновенно.
 *
 * - gcTime: 5 минут — после 5 минут без использования данные удаляются из кэша.
 *
 * - retry: 1 — при ошибке запрос повторяется один раз.
 *   Полезно для временных сбоев сети. Для 401/403/404 повтор не нужен —
 *   это ошибки клиента, повтор их не исправит. Логика ретраев с учётом
 *   статуса — в shared/api/http.js (будет позже).
 *
 * - refetchOnWindowFocus: false — НЕ перезапрашивать данные при
 *   переключении обратно на вкладку. Иначе каждый раз при alt+tab
 *   страница мигает. Кнопка «Обновить» на страницах будет работать явно.
 *
 * - refetchOnReconnect: true — при восстановлении соединения обновить данные.
 *   Это полезно в LAN, где Wi-Fi может пропадать.
 */
export const queryClient = new QueryClient({
  defaultOptions: {
    queries: {
      staleTime: 30_000,
      gcTime: 5 * 60_000,
      retry: 1,
      refetchOnWindowFocus: false,
      refetchOnReconnect: true,
    },
    mutations: {
      retry: 0,
    },
  },
})
